"""The paperclip on a message bubble (Kris, 2026-09-20).

"A clickable paperclip icon to the message box, even when collapsed,
whenever there's an attachment — an outgoing invoice has an attachment,
incoming emails with documents have attachments. When clicked, it opens the
attachment directly." Incoming files live on the record (crm_artifacts,
remembering the email they came from); an invoice's PDF is regenerated by
/app/invoices/{id}/pdf, found by the stamp on its email row or, for older
rows, by the reference in the subject.

Run: python -m pytest tests/test_thread_attachments.py -q
"""
from pathlib import Path

import pytest
from fastapi.testclient import TestClient

import app.dashboard as dashboard
from app import db, invoice_send
from app.auth import TenantCtx, require_onboarded
from app.main import app

CLIP = 'class="attachment-clip'


@pytest.fixture
def client():
    app.dependency_overrides[require_onboarded] = lambda: TenantCtx(tenant_id="t1", client=None)
    yield TestClient(app)
    app.dependency_overrides.clear()


def _env(monkeypatch, items, docs=(), invoices=()):
    monkeypatch.setattr(dashboard.db, "get_conversation", lambda *a, **k: [dict(i) for i in items])
    monkeypatch.setattr(dashboard.db, "list_email_log", lambda *a, **k: [])
    monkeypatch.setattr(dashboard.db, "active_modules", lambda *a, **k: set())
    monkeypatch.setattr(dashboard.db, "get_tenant", lambda *a, **k: {"name": "T"})
    monkeypatch.setattr(dashboard.db, "is_enterprise", lambda *a, **k: False)
    monkeypatch.setattr(dashboard.billing, "has_active_subscription", lambda *a, **k: False)
    monkeypatch.setattr(dashboard.db, "list_documents", lambda *a, **k: [dict(d) for d in docs])
    by_ref = {i["invoice_ref"]: i for i in invoices}
    monkeypatch.setattr(dashboard.db, "get_invoice_by_ref", lambda t, ref, **k: by_ref.get(ref))


def _row(status, **kw):
    return {"id": kw.pop("id", "x"), "status": status, "body_in": "Hi, card attached.",
            "draft_reply": "Thanks, got it.", "created_at": "2026-09-20T09:00:00",
            "subject": "Re: Boarding for Biscuit", **kw}


def test_an_incoming_attachment_puts_a_clip_on_the_customer_bubble_even_collapsed(client, monkeypatch):
    _env(monkeypatch, [_row("sent", id="a"), _row("sent", id="b")],
         docs=[{"id": "doc1", "filename": "vaccination-card.pdf", "email_log_id": "b"}])
    html = client.get("/app/conversations/view?contact=hannah@x.co").text
    # the stage's resting face (the header line, visible while collapsed) carries it
    face = html[html.index('id="stage-bubble"'):html.index('id="stage-bubble-body"')]
    assert CLIP in face and 'href="/app/crm/documents/doc1"' in face
    assert 'aria-label="Open vaccination-card.pdf"' in face
    # the history page for that round carries it on the customer's bubble; round "a" has none
    page_a = html[html.index('id="log-a"'):html.index('id="log-b"')]
    page_b = html[html.index('id="log-b"'):]
    assert CLIP not in page_a and 'href="/app/crm/documents/doc1"' in page_b


def test_a_sent_invoice_carries_its_pdf_by_stamp_or_by_reference(client, monkeypatch):
    stamped = _row("sent", id="a", kind="invoice", subject="Invoice INV-1001",
                   source_message_id="invoice:11111111-2222-3333-4444-555555555555:sent",
                   draft_reply="Please find attached invoice INV-1001", body_in="[invoice]")
    older = _row("sent", id="b", kind="invoice", subject="Invoice INV-0999",
                 draft_reply="Please find attached invoice INV-0999", body_in="[invoice]")
    _env(monkeypatch, [stamped, older], invoices=[{"id": "old-id", "invoice_ref": "INV-0999"}])
    html = client.get("/app/conversations/view?contact=hannah@x.co").text
    assert 'href="/app/invoices/11111111-2222-3333-4444-555555555555/pdf"' in html   # by the stamp
    assert 'href="/app/invoices/old-id/pdf"' in html                                  # by the reference
    assert 'aria-label="Open INV-1001.pdf"' in html and 'aria-label="Open INV-0999.pdf"' in html
    # the newest round's reply is the stage's own bubble — it carries the clip too
    stage_reply = html[html.rindex("AI · Sent"):]
    assert CLIP in stage_reply


def test_a_plain_thread_has_no_clip(client, monkeypatch):
    _env(monkeypatch, [_row("sent", id="a")])
    assert CLIP not in client.get("/app/conversations/view?contact=hannah@x.co").text


def test_the_invoice_pdf_route_serves_the_file_inline(client, monkeypatch):
    from app import invoice_pdf
    monkeypatch.setattr(dashboard.db, "get_invoice", lambda i, t, **k: {"id": i, "invoice_ref": "INV-1001", "total": 22.88})
    monkeypatch.setattr(dashboard.db, "list_invoice_lines", lambda *a, **k: [])
    monkeypatch.setattr(dashboard.db, "get_invoice_settings", lambda *a, **k: {})
    monkeypatch.setattr(invoice_pdf, "render", lambda inv, lines, s: b"%PDF-1.4 test")
    r = client.get("/app/invoices/abc/pdf")
    assert r.status_code == 200 and r.headers["content-type"].startswith("application/pdf")
    assert r.headers["content-disposition"] == 'inline; filename="INV-1001.pdf"'
    assert r.content == b"%PDF-1.4 test"
    monkeypatch.setattr(dashboard.db, "get_invoice", lambda *a, **k: None)
    assert client.get("/app/invoices/nope/pdf").status_code == 404


def test_sending_an_invoice_stamps_its_email_row(monkeypatch):
    seen = {}
    monkeypatch.setattr(db, "insert_email_log", lambda *a, **k: (seen.update(k) or ("log-1", True)))
    monkeypatch.setattr(db, "mark_email_log_sent", lambda *a, **k: None)
    invoice_send._log_sent_email("t1", "hannah@x.co", "Invoice INV-1001", "body", kind="invoice",
                                 via="owner", source_message_id="invoice:inv-1:sent")
    assert seen["source_message_id"] == "invoice:inv-1:sent" and seen["kind"] == "invoice"
    src = (Path(__file__).resolve().parents[1] / "src/app/invoice_send.py").read_text(encoding="utf-8")
    assert 'source_message_id=f"invoice:{invoice_id}:sent"' in src
